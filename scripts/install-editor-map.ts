import { readFile, writeFile, mkdir, readdir, stat, rename, access } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateMapDocument, type MapDocument } from '../packages/winterarc-world/index.js';

/** Run locally before deploying. Never accepts or evaluates JavaScript map files. */
async function main(): Promise<void> {
  const args = process.argv.slice(2);
  if (!args[0] || args.includes('--help')) {
    console.log('npm run map:install -- ./village.map.json [--force]');
    return;
  }
  const input = resolve(args[0]);
  if ((await stat(input)).size > 32 * 1024 * 1024) throw new Error('Map exceeds 32 MB');
  const doc = JSON.parse(await readFile(input, 'utf8')) as MapDocument;
  validateMapDocument(doc);
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const directory = resolve(root, 'packages/winterarc-world/src/maps');
  await mkdir(directory, { recursive: true });
  const destination = resolve(directory, `${doc.mode}.json`);
  let exists = false;
  try { await access(destination); exists = true; } catch { /* New file. */ }
  if (exists && !args.includes('--force')) throw new Error('Map already exists. Pass --force to replace it.');
  const maps: Record<string, MapDocument> = {};
  for (const file of (await readdir(directory)).sort()) {
    if (!/^(hunt|giftrace|crab|icebreak|knockout|colorfall)\.json$/.test(file) || file === `${doc.mode}.json`) continue;
    const other = JSON.parse(await readFile(resolve(directory, file), 'utf8')) as MapDocument;
    validateMapDocument(other);
    if (file !== `${other.mode}.json`) throw new Error(`Mode/filename mismatch: ${file}`);
    maps[other.mode] = other;
  }
  maps[doc.mode] = doc;
  const registry = `import type { GameId } from 'winterarc-core';\nimport type { MapDocument } from '../MapDocument.js';\n// Generated by map:install.\nexport const importedMaps: Partial<Record<GameId, MapDocument>> = ${JSON.stringify(maps)};\n`;
  await writeFile(destination + '.tmp', JSON.stringify(doc) + '\n');
  await writeFile(resolve(directory, 'generated.ts.tmp'), registry);
  await rename(destination + '.tmp', destination);
  await rename(resolve(directory, 'generated.ts.tmp'), resolve(directory, 'generated.ts'));
  console.log(`Installed ${doc.name} for ${doc.mode}. Rebuild/deploy BOTH web and server from this source.`);
}
void main().catch(error => { console.error(error instanceof Error ? error.message : error); process.exitCode = 1; });
